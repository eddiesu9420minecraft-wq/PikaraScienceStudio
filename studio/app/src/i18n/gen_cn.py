# Regenerate i18n/zh-CN.js from every CJK string literal in js/**/*.js and index.html.
# Usage: python studio/app/src/i18n/gen_cn.py   (needs `pip install opencc`)
import json, pathlib, re
import opencc

SRC = pathlib.Path(__file__).resolve().parent.parent
CC = opencc.OpenCC("tw2sp")
CJK = re.compile(r"[㐀-鿿]")
# corrections after tw2sp (keep UI wording natural for mainland users)
FIX = {"视讯": "视频", "音讯": "音频", "预设": "默认", "缺省": "默认", "档案": "文件", "资料夹": "文件夹", "回滚": "回滚", "接口语言": "界面语言", "接口": "界面"}

strings = set()
for f in list(SRC.glob("js/**/*.js")) + [SRC / "index.html"]:
    text = f.read_text(encoding="utf-8")
    text = re.sub(r"^\s*//.*$", "", text, flags=re.M)  # drop line comments
    for m in re.finditer(r"'((?:[^'\\\n]|\\.)*)'|\"((?:[^\"\\\n]|\\.)*)\"", text):
        s = next(g for g in m.groups() if g is not None)
        if CJK.search(s):
            strings.add(s)

table = {}
for s in sorted(strings):
    c = CC.convert(s)
    for a, b in FIX.items():
        c = c.replace(a, b)
    if c != s:
        table[s] = c

out = "// Generated by gen_cn.py (OpenCC tw2sp) — do not edit by hand.\nexport default " + json.dumps(table, ensure_ascii=False, indent=0) + ";\n"
(SRC / "i18n" / "zh-CN.js").write_text(out, encoding="utf-8")
print(f"{len(strings)} strings, {len(table)} converted")
